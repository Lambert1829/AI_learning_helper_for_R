async (page) => {
  const checks = [], requests = [], errors = [];
  const check = (ok, name) => { if (!ok) throw Error(name); checks.push(name); };
  const requestListener = request => { if (request.method() === 'POST' && /\/api\/(chat|review)$/.test(request.url())) requests.push({url:request.url(),body:request.postDataJSON()}); };
  const errorListener = error => errors.push(error.message);
  page.on('request',requestListener); page.on('pageerror',errorListener);
  const route = async view => {
    await page.evaluate(view => { location.hash = '/' + view; },view);
    await page.waitForFunction(view => document.querySelector('#main-nav a[aria-current="page"]')?.hash === '#/' + view, view);
  };
  const ready = async () => page.waitForFunction(() => !document.querySelector('#send').disabled);
  const responseAfter = async action => {
    const count = await page.locator('.message').count();
    await action();
    await page.waitForFunction(n => document.querySelectorAll('.message').length === n+1, count);
    await ready();
  };
  const submit = async question => { await page.locator('#question').fill(question); await responseAfter(() => page.locator('#send').click()); };
  const more = async name => { await page.locator('#more-toggle').click(); await page.getByRole('button',{name,exact:true}).filter({visible:true}).click(); };
  const noOverflow = async name => check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.body.scrollWidth <= innerWidth),name);
  try {
    await page.context().grantPermissions(['clipboard-read','clipboard-write']);
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:8000');
    await page.evaluate(() => localStorage.removeItem('r-tutor-mock-v1'));
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll('.knowledge-item').length === 43);
    check(await page.locator('#home-view').isVisible(),'default home');
    check((await page.locator('.hero h1').textContent()) === 'R语言学习，从一个问题开始','hero title');
    await noOverflow('desktop home width');
    await page.locator('.reveal').first().evaluate(async n => { await Promise.all(n.getAnimations().map(a => a.finished)); });
    await page.screenshot({path:'output/playwright/v2-desktop-home.png',fullPage:true});
    await page.locator('.hero-actions a').first().click();
    await page.waitForFunction(() => !document.querySelector('#layout').hidden);
    check(await page.locator('#welcome').isVisible(),'first visit examples');
    await page.locator('#catalog-toggle').click();
    check(await page.locator('#layout').evaluate(n => n.classList.contains('sidebar-collapsed')),'desktop collapse');
    await page.locator('#catalog-toggle').click();
    await page.locator('#catalog .unit').nth(1).locator('summary').click();
    await page.waitForFunction(() => document.querySelectorAll('#catalog .unit[open]').length === 1);
    check(await page.locator('#catalog .unit').nth(1).evaluate(n => n.open),'single expanded unit');
    await responseAfter(() => page.getByRole('button',{name:'缺失值与均值',exact:true}).click());
    check(await page.locator('#welcome').isHidden(),'hide examples after response');
    check((await page.locator('.message').last().textContent()).includes('na.rm'),'course answer');
    await responseAfter(() => page.locator('.message').last().getByRole('button',{name:'例题',exact:true}).click());
    check(requests.at(-1).body.question === '举个例子','example label maps existing request');
    await responseAfter(() => page.locator('.message').last().getByRole('button',{name:'易错点',exact:true}).click());
    check(requests.at(-1).body.question === '有什么易错点' && requests.at(-1).body.knowledge_id === 'K06','three turn followup context');
    await responseAfter(() => page.locator('.message').last().getByRole('button',{name:'练习',exact:true}).click());
    check(requests.at(-1).body.question === '给我练习','exercise label maps existing request');
    await page.locator('.message').last().getByRole('button',{name:'继续提问',exact:true}).click();
    check(await page.locator('#question').evaluate(n => n === document.activeElement),'continue focus');
    await submit('factor中的levels有什么作用？');
    check((await page.locator('#current-topic').textContent()).includes('K07'),'explicit topic switch');
    await route('review');
    check(await page.locator('#code-panel').isVisible(),'review opens code');
    await page.locator('#code').fill('x <- c(1, NA, 3)\nx[x == NA]');
    await page.locator('#error-message').fill('NA');
    await submit('为什么不能用x == NA判断缺失？');
    check(requests.at(-1).url.endsWith('/api/review'),'existing review endpoint');
    check((await page.locator('.message').last().textContent()).includes('is.na'),'reference correction');
    check(await page.locator('.message').last().locator('.unverified').count() === 1,'single unverified label');
    await page.locator('.message').last().getByRole('button',{name:'复制代码',exact:true}).last().click();
    check((await page.evaluate(() => navigator.clipboard.readText())).includes('is.na'),'copy code');
    await page.evaluate(() => { window.__clipboard = navigator.clipboard.writeText; navigator.clipboard.writeText = () => Promise.reject(new Error('test denied')); return true; });
    await page.locator('.message').last().locator('.copy').last().click();
    check((await page.locator('#status').textContent()).includes('复制失败'),'copy failure feedback');
    await page.evaluate(() => { navigator.clipboard.writeText = window.__clipboard; delete window.__clipboard; });
    await page.locator('#code-toggle').click();
    check(await page.locator('#code-panel').isHidden(),'collapse code');
    await submit('mean中的na.rm怎么用？');
    check(requests.at(-1).body.code === '' && requests.at(-1).body.error_message === '' && requests.at(-1).url.endsWith('/api/chat'),'hidden code not submitted');
    const sources = page.locator('.message').last().locator('.sources');
    check(!(await sources.getAttribute('open')) && await sources.evaluate(n => !n.open),'sources collapsed');
    await sources.locator('summary').click();
    await responseAfter(() => sources.getByRole('button',{name:'K06',exact:true}).first().click());
    check(page.url().endsWith('#/chat'),'source opens explanation in chat');
    await submit('电影数据清洗综合练习');
    await responseAfter(() => page.locator('.message').last().getByRole('button',{name:'参考答案',exact:true}).click());
    check(requests.at(-1).body.teaching_mode === 'solution','reference answer switch');
    const output = page.locator('.message').last().locator('.reference-output');
    check(await output.count() === 1 && await output.evaluate(n => !n.open),'reference output collapsed');
    await output.locator('summary').click();
    await page.screenshot({path:'output/playwright/v2-desktop-chat.png',fullPage:true});
    await route('knowledge');
    check(await page.locator('.map-unit').count() === 8,'eight map units');
    await page.locator('#map-search').fill('K06');
    check(await page.locator('.knowledge-item').count() === 1,'map search');
    check((await page.locator('.knowledge-item').textContent()).includes('K04'),'real prerequisite');
    await responseAfter(() => page.locator('.knowledge-title').click());
    check(page.url().endsWith('#/chat'),'map topic starts chat');
    await page.locator('#question').fill('保留问题草稿');
    await page.locator('#code-toggle').click();
    await page.locator('#code').fill('draft <- 1');
    await route('home'); await route('review');
    check(await page.locator('#question').inputValue() === '保留问题草稿' && await page.locator('#code').inputValue() === 'draft <- 1','route retains drafts');
    await route('history');
    const count = await page.locator('.message').count();
    check(await page.locator('.history-row').count() === count,'history list');
    await page.locator('.history-row').last().click();
    check(await page.locator('#record-0').evaluate(n => n === document.activeElement),'history return focus');
    await page.reload(); await ready();
    check(await page.locator('.message').count() === count,'legacy storage restore');
    await route('history');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#history-export').click();
    const download = await downloadPromise; await download.saveAs('output/playwright/v2-records.json');
    check(download.suggestedFilename().endsWith('.json'),'export JSON');
    await more('当前版本说明');
    check(await page.locator('#version-dialog').isVisible(),'version dialog');
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => document.activeElement === document.querySelector('#more-toggle'));
    check(await page.locator('#version-dialog').evaluate(n => !n.open),'dialog restores focus');
    await page.locator('#more-toggle').focus(); await page.keyboard.press('ArrowDown');
    check(await page.locator('#more-panel a').evaluate(n => n === document.activeElement),'more keyboard opening');
    await page.keyboard.press('Escape');
    check(await page.locator('#more-toggle').evaluate(n => n === document.activeElement),'more Escape focus');
    await route('home'); await route('knowledge'); await page.goBack();
    await page.waitForFunction(() => !document.querySelector('#home-view').hidden);
    await page.goForward(); await page.waitForFunction(() => !document.querySelector('#knowledge-view').hidden);
    check(true,'back and forward navigation');
    await route('chat');
    await submit('<img src=x onerror="window.__injected=1">');
    check(await page.evaluate(() => !window.__injected && !document.querySelector('#messages img')),'safe input rendering');
    check((await page.locator('.message').last().textContent()).includes('<img'),'literal HTML visible');
    await submit('火星旅行机票价格');
    check((await page.evaluate(() => JSON.parse(localStorage.getItem('r-tutor-mock-v1')).at(-1).response.status)) === 'no_match','no match normal response');
    const failure = route => route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({error:{message:'测试参数错误'}})});
    await page.route('**/api/chat', failure); await page.locator('#question').fill('mean'); await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('测试参数错误')); await ready();
    check(true,'API validation error and button recovery'); await page.unroute('**/api/chat',failure);
    const offline = route => route.abort('connectionrefused');
    await page.route('**/api/chat', offline); await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('无法连接本地服务')); await ready();
    check(true,'connection failure and button recovery'); await page.unroute('**/api/chat',offline);
    await submit('mean中的na.rm怎么用？');
    check(await page.locator('#status').isHidden(),'successful retry clears error');
    await page.locator('.skip-link').focus(); await page.keyboard.press('Enter');
    check(page.url().endsWith('#/chat') && await page.locator('#main-content').evaluate(n => n === document.activeElement),'skip link preserves workspace');
    for (const view of ['home','knowledge','history','chat','review']) { await route(view); await noOverflow('desktop '+view+' layout'); }
    await page.setViewportSize({width:390,height:844});
    await route('chat'); await submit('mean中的na.rm怎么用？');
    check(requests.at(-1).url.endsWith('/api/chat'),'mobile chat submission');
    await route('review'); await page.locator('#code').fill('x <- c(1, NA, 3)\nx[x == NA]');
    await submit('为什么不能用x == NA判断缺失？');
    check((await page.locator('.message').last().textContent()).includes('is.na'),'mobile review submission');

    for (const view of ['home','knowledge','history','chat','review']) {
      await route(view); await noOverflow('mobile '+view+' layout');
      await page.screenshot({path:'output/playwright/v2-mobile-'+view+'.png',fullPage:true});
    }
    await route('chat');
    await page.locator('#nav-toggle').click();
    check(await page.locator('#main-nav').isVisible(),'mobile nav opens');
    await page.locator('#main-nav a[href="#/knowledge"]').click();
    await page.waitForFunction(() => !document.querySelector('#knowledge-view').hidden);
    check(!(await page.locator('#main-nav').isVisible()),'mobile nav closes after selection');
    await page.locator('#nav-toggle').click(); await page.keyboard.press('Escape');
    check(await page.locator('#nav-toggle').evaluate(n => n === document.activeElement),'mobile nav Escape focus');
    await route('chat'); await page.locator('#catalog-toggle').click();
    check(await page.locator('#sidebar').getAttribute('aria-modal') === 'true','mobile drawer');
    await page.locator('#sidebar-close').focus(); await page.keyboard.press('Shift+Tab');
    check(await page.evaluate(() => document.querySelector('#sidebar').contains(document.activeElement)),'drawer focus trap');
    await page.keyboard.press('Escape');
    check(await page.locator('#catalog-toggle').evaluate(n => n === document.activeElement),'drawer restores focus');
    check(await page.locator('#catalog-toggle').evaluate(n => getComputedStyle(n).outlineStyle !== 'none'),'visible keyboard focus');
    const targets = await page.locator('button:visible, #main-nav a:visible, .primary:visible').evaluateAll(nodes => nodes.filter(n => n.getBoundingClientRect().height < 44 || n.getBoundingClientRect().width < 44).map(n => n.textContent));
    check(targets.length === 0,'mobile touch targets');
    await page.emulateMedia({reducedMotion:'reduce'}); await route('home');
    check(await page.locator('.reveal').first().evaluate(n => getComputedStyle(n).animationName === 'none'),'reduced motion');
    await route('history'); await page.locator('#history-clear').click(); await page.reload();
    check(await page.locator('.message').count() === 0 && await page.locator('.history-row').count() === 0,'clear persists');
    await route('chat'); check(await page.locator('#welcome').isVisible(),'examples return after clear');
    check(errors.length === 0,'no uncaught browser errors');
    await route('home');
    return {passed:checks.length,checks,errors};
  } finally { page.off('request',requestListener); page.off('pageerror',errorListener); }
}
