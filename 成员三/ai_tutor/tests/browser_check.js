async (page) => {
  const checks=[];
  const check=(condition,name)=>{if(!condition)throw Error(name);checks.push(name);};
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.goto('http://127.0.0.1:8000');
  await page.getByRole('button',{name:'清空记录',exact:true}).click();
  await page.getByRole('button',{name:'缺失值与均值',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1);
  check((await page.locator('.summary').last().textContent()).length>0,'course question');
  await page.locator('.message').last().getByRole('button',{name:'举个例子',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===2);
  await page.locator('.message').last().getByRole('button',{name:'有什么易错点',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===3);
  check((await page.locator('.message').last().textContent()).includes('NA'),'three turn followup');
  await page.getByRole('button',{name:'试试代码纠错',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===4);
  check((await page.locator('.message').last().textContent()).includes('is.na'),'debug reference');
  await page.locator('.message').last().getByRole('button',{name:'复制代码',exact:true}).last().click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).includes('is.na'),'clipboard');
  await page.locator('.message').last().getByRole('button',{name:'K06',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('#knowledge-title').textContent.startsWith('K06'));
  check(await page.locator('#knowledge-panel').isVisible(),'source navigation');
  await page.reload();
  check(await page.locator('.message').count()===4,'history restore');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出JSON',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs('output/playwright/export.json');
  check(download.suggestedFilename().endsWith('.json'),'export download');
  await page.getByRole('button',{name:'清空记录',exact:true}).click();
  await page.reload();
  check(await page.locator('.message').count()===0,'clear persists');
  await page.getByLabel('你的问题').fill('<img src=x onerror="window.__injected=1">');
  await page.getByRole('button',{name:'发送问题 →',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1);
  check(await page.evaluate(()=>!window.__injected&&!document.querySelector('#messages img')),'safe text rendering');
  check((await page.locator('.summary').last().textContent()).includes('未找到'),'no match');
  await page.getByRole('button',{name:'清空记录',exact:true}).click();
  await page.getByLabel('任务类型').selectOption('exercise');
  await page.getByLabel('你的问题').fill('对模拟电影表清洗日期，保留评分≥7的电影，按评分降序，计算各类型均分。');
  await page.getByRole('button',{name:'发送问题 →',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1);
  check(await page.locator('.message').last().locator('pre').count()===0,'exercise hint hides code');
  await page.locator('.message').last().getByRole('button',{name:'查看参考答案',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===2);
  check(await page.locator('.message').last().locator('pre').count()>0,'exercise solution');
  await page.getByRole('button',{name:'清空记录',exact:true}).click();
  await page.getByRole('button',{name:'试试代码纠错',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1);
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>window.scrollTo(0,0));
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile no horizontal overflow');
  await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
  await page.getByRole('button',{name:'清空记录',exact:true}).click();
  await page.getByRole('button',{name:'向量与列表',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.message').length===1);
  check((await page.locator('.summary').textContent()).includes('列表'),'mobile question');
  return {checks,passed:checks.length};
}
